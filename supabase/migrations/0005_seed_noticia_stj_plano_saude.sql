Uma decisão recente do Superior Tribunal de Justiça trouxe importante repercussão financeira para empresas que contratam planos coletivos de assistência à saúde. Em maio de 2026, a Terceira Turma considerou inexigíveis as mensalidades cobradas durante os 60 dias posteriores ao pedido de cancelamento de um plano de saúde coletivo empresarial.

O julgamento ocorreu no Recurso Especial 2.260.667/SP, relatado pela ministra Daniela Teixeira. Por unanimidade, a turma não conheceu do recurso apresentado pela operadora e manteve a decisão que havia afastado a cobrança. O acórdão foi publicado em 14 de maio de 2026. [Consulte o acórdão no STJ](https://processo.stj.jus.br/SCON/pesquisar.jsp?O=RR&b=ACOR&p=true&preConsultaPP=000005061%2F0&thesaurus=JURIDICO&tp=T).

## O que estava em discussão

O contrato continha uma cláusula segundo a qual, mesmo depois de pedir o cancelamento, a empresa deveria continuar pagando as mensalidades por mais 60 dias. A operadora defendia que a regra havia sido livremente pactuada e estaria amparada pelos princípios da liberdade contratual, da boa-fé e da função social dos contratos.

Também argumentava que o artigo 23 da Resolução Normativa 557/2022 da Agência Nacional de Saúde Suplementar permitiria que as condições de rescisão fossem definidas no próprio contrato.

O STJ, entretanto, concluiu que essa norma da ANS apenas determina que as condições de cancelamento constem do instrumento contratual. Ela não autoriza a imposição de um aviso prévio remunerado de 60 dias — isto é, a obrigação de pagar por dois meses depois de manifestada a vontade de encerrar o plano.

Segundo o acórdão, exigir esse pagamento coloca o contratante em desvantagem exagerada, pois o obriga a custear um serviço que já informou não pretender continuar utilizando.

## Por que a cobrança foi considerada abusiva

A exigência dos 60 dias surgiu no parágrafo único do artigo 17 da antiga RN 195/2009 da ANS. Esse dispositivo determinava que os planos coletivos somente poderiam ser rescindidos sem motivo depois de 12 meses de vigência e mediante notificação com antecedência mínima de 60 dias.

A regra foi anulada em ação civil pública — processo 0136265-83.2013.4.02.5101 — com decisão transitada em julgado e eficácia nacional. Posteriormente, a própria ANS retirou o dispositivo de sua regulamentação.

A atual RN 557/2022 não restabeleceu a obrigação. Seu artigo 23 limita-se a exigir que as condições de rescisão ou suspensão estejam previstas no contrato. Em avaliação regulatória, a ANS também reconheceu que atualmente não há, para os contratos coletivos em geral, um prazo mínimo regulamentar de vigência ou de aviso prévio. [Veja a avaliação regulatória da ANS](https://www.gov.br/ans/pt-br/acesso-a-informacao/transparencia-e-prestacao-de-contas/ARR_Reajuste_Planos_Coletivos.pdf).

Para o STJ, uma disposição declarada abusiva não pode ser recuperada simplesmente porque passou a constar expressamente do contrato. A autonomia das partes não legitima cláusula que imponha uma obrigação excessivamente onerosa ao contratante.

## Qual é a economia possível para as empresas

O efeito econômico aparece principalmente na substituição ou no encerramento do plano empresarial.

Imagine uma empresa que pague R$ 25 mil por mês e decida migrar seus empregados para outra operadora. Se a antiga operadora exigir 60 dias adicionais, o custo de saída poderá alcançar R$ 50 mil — eventualmente somado ao pagamento do novo contrato durante o mesmo período.

Com o entendimento reafirmado pelo STJ, essa cobrança pode ser contestada. A decisão, portanto, não reduz o preço mensal do plano atual, nem cria um teto para os reajustes. O que ela pode eliminar é o custo de dois meses imposto depois do pedido de cancelamento.

A distinção é relevante: não se trata de desconto, revisão da sinistralidade ou redução geral das mensalidades. Trata-se da inexigibilidade de uma despesa associada ao encerramento do contrato.

## A decisão vale para qualquer cancelamento?

O julgamento trata do cancelamento do contrato coletivo pela pessoa jurídica contratante. Não deve ser confundido com:

* a exclusão isolada de um empregado ou dependente;
* a rescisão promovida pela própria operadora;
* o cancelamento por inadimplência;
* a manutenção do plano para beneficiário internado ou submetido a tratamento médico;
* a portabilidade de carências para outro plano.

Essas situações possuem regras próprias.

Também é necessário observar que o REsp 2.260.667/SP não foi julgado pelo rito dos recursos repetitivos. Tecnicamente, portanto, ele não criou uma tese vinculante semelhante aos temas repetitivos do STJ. Ainda assim, o acórdão afirma que a jurisprudência da corte já está consolidada no sentido da nulidade da cláusula e se apoia em uma ação civil pública com eficácia nacional.

## O Código de Defesa do Consumidor pode proteger a empresa?

No processo, reconheceu-se a incidência do Código de Defesa do Consumidor com base na chamada teoria finalista mitigada. Por essa abordagem, pequenas e médias empresas podem receber proteção consumerista quando demonstrada sua vulnerabilidade técnica, jurídica ou econômica diante da operadora.

Isso não significa que toda pessoa jurídica será automaticamente considerada consumidora. Grandes empresas com efetiva capacidade de negociação podem enfrentar uma análise diferente. A vulnerabilidade, o conteúdo do contrato e as circunstâncias da contratação continuam relevantes.

A decisão, contudo, vai além desse ponto ao registrar que a jurisprudência do STJ considera nula a cláusula de aviso prévio remunerado nos planos coletivos em razão da invalidação judicial da antiga norma da ANS.

## O que as empresas devem fazer

Empresas que estejam avaliando a troca ou o cancelamento do plano devem formalizar o pedido por escrito, guardar o protocolo e indicar claramente a data pretendida para o encerramento. Também é recomendável verificar se a operadora continuou cobrando mensalidades ou manteve o serviço ativo sem solicitação após o pedido.

Contratos que ainda prevejam aviso prévio remunerado de 60 dias merecem revisão. Se os valores já tiverem sido pagos, a possibilidade de restituição dependerá da documentação, das datas das cobranças, das circunstâncias do contrato e dos prazos aplicáveis ao caso concreto.

Ao mesmo tempo, a empresa deve planejar a transição para não deixar empregados e dependentes sem cobertura, comunicar os beneficiários e verificar eventuais direitos de portabilidade ou continuidade de tratamento. A orientação pública da ANS confirma que as condições de cancelamento dos planos coletivos devem estar previstas no contrato e que os beneficiários precisam ser informados sobre o encerramento e a portabilidade de carências. [Consulte as orientações da ANS](https://www.gov.br/ans/pt-br/assuntos/contratacao-e-troca-de-plano/dicas-de-como-escolher-um-plano-de-saude-1/saiba-antes-de-contratar-um-plano).

## Conclusão

A decisão do STJ representa uma oportunidade concreta de redução do custo de saída dos planos de saúde empresariais. Ao afastar a cobrança automática de dois meses após o pedido de cancelamento, o tribunal reforça que a simples inclusão de uma obrigação no contrato não elimina o controle de abusividade.

O precedente não interfere diretamente no valor das mensalidades ou nos reajustes anuais. Seu impacto está em permitir que empresas encerrem ou substituam o benefício sem suportar um aviso prévio remunerado cuja base regulamentar já foi anulada.

